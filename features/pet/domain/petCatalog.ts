/** 전체 펫 — 프리즘 펫이 먼저, 그다음 코인 펫 (종·색 이름순) */
export const PETS: PetDef[] = [
  ...PREMIUM_IDS.map((id) => define(id, true)),
  ...FREE_IDS.map((id) => define(id, false)),
];

const BY_ID = new Map(PETS.map((p) => [p.id, p]));

export function petById(id: string): PetDef | undefined {
  return BY_ID.get(id);
}

/** 펫별 채굴력 표 — 서버가 DB 함수(check_in)에 그대로 넘긴다 */
export const PET_POWER: Record<string, number> = Object.fromEntries(
  PETS.map((p) => [p.id, p.power])
);

/** 팀 채굴력 합 — 시간당 게이지를 정한다 (mining.ts의 pointsPerHour) */
export function miningPower(team: string[]): number {
  return team.reduce((sum, id) => sum + (petById(id)?.power ?? 1), 0);
}
