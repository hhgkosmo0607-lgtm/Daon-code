/** 원본 폴더 이름(free/premium) → 재화·채굴력 */
function define(id: string, premium: boolean): PetDef {
  const [species, color] = id.split('_');
  return {
    id,
    species,
    color,
    currency: premium ? 'prism' : 'coin',
    power: premium ? 3 : 1,
    label:
      LABEL_OVERRIDE[id] ?? `${COLOR_LABEL[color] ?? color} ${SPECIES_LABEL[species] ?? species}`,
  };
}

